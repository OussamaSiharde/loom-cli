package dev.loom;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Holds every user choice. Mutable on purpose: CLI flags and interactive
 * prompts both write into it, then {@link #normalize()} enforces the
 * compatibility rules and reports what it changed.
 */
public final class Spec {

    public String name = "demo";
    public String groupId = "com.example";
    public String packageName = null;   // derived from groupId + name when null
    public String lang = "java";        // java | kotlin
    public String boot = "3";           // 3 | 2   (Boot 3.x Jakarta vs Boot 2.7 javax)
    public String bootVersion = null;   // explicit override, e.g. --boot-version 3.4.5
    public String javaVersion = "21";   // 8 | 11 | 17 | 21
    public String web = "mvc";          // mvc | webflux | none
    public String server = "tomcat";    // tomcat | undertow | jetty | netty
    public String http = "none";        // none | restclient | webclient | resttemplate
    public String db = "none";          // postgres | mysql | mariadb | mongo | h2 | none
    public String data = "auto";        // auto | jpa | jdbc | r2dbc | mongo
    public String migrations = "none";  // flyway | liquibase | none
    public String cache = "none";       // none | caffeine | redis
    public String mq = "none";          // none | rabbitmq | kafka | artemis
    public String json = "jackson";     // jackson | gson
    public String logging = "logback";  // logback | log4j2
    public String tests = "junit";      // junit | testng
    public String mock = "mockito";     // mockito | easymock | none
    public boolean tc = false;          // Testcontainers
    public boolean jacoco = true;
    public boolean lombok = false;
    public boolean openapi = false;
    public boolean actuator = true;
    public boolean docker = true;
    public boolean ci = true;
    public boolean zip = false;
    public boolean force = false;
    public String out = ".";
    public String description = "Generated by Loom";

    static final Map<String, List<String>> ALLOWED = Map.ofEntries(
            Map.entry("lang", List.of("java", "kotlin")),
            Map.entry("boot", List.of("3", "2")),
            Map.entry("java", List.of("8", "11", "17", "21")),
            Map.entry("web", List.of("mvc", "webflux", "none")),
            Map.entry("server", List.of("tomcat", "undertow", "jetty", "netty")),
            Map.entry("http", List.of("none", "restclient", "webclient", "resttemplate")),
            Map.entry("db", List.of("postgres", "mysql", "mariadb", "mongo", "h2", "none")),
            Map.entry("data", List.of("auto", "jpa", "jdbc", "r2dbc", "mongo")),
            Map.entry("migrations", List.of("flyway", "liquibase", "none")),
            Map.entry("cache", List.of("none", "caffeine", "redis")),
            Map.entry("mq", List.of("none", "rabbitmq", "kafka", "artemis")),
            Map.entry("json", List.of("jackson", "gson")),
            Map.entry("logging", List.of("logback", "log4j2")),
            Map.entry("tests", List.of("junit", "testng")),
            Map.entry("mock", List.of("mockito", "easymock", "none"))
    );

    public static Spec defaults() {
        return new Spec();
    }

    /** Applies CLI flags. Exits with a clear message on unknown keys/values. */
    public void apply(Map<String, String> flags) {
        for (Map.Entry<String, String> e : flags.entrySet()) {
            String k = e.getKey();
            String v = e.getValue();
            switch (k) {
                case "name" -> name = v;
                case "group" -> groupId = v;
                case "package" -> packageName = v;
                case "lang" -> lang = pick("lang", v);
                case "boot" -> boot = pick("boot", v);
                case "boot-version" -> bootVersion = v;
                case "java" -> javaVersion = pick("java", v);
                case "web" -> web = pick("web", v);
                case "server" -> server = pick("server", v);
                case "http" -> http = pick("http", v);
                case "db" -> db = pick("db", v);
                case "data" -> data = pick("data", v);
                case "migrations" -> migrations = pick("migrations", v);
                case "cache" -> cache = pick("cache", v);
                case "mq" -> mq = pick("mq", v);
                case "json" -> json = pick("json", v);
                case "logging" -> logging = pick("logging", v);
                case "tests" -> tests = pick("tests", v);
                case "mock" -> mock = pick("mock", v);
                case "tc" -> tc = bool(k, v);
                case "jacoco" -> jacoco = bool(k, v);
                case "lombok" -> lombok = bool(k, v);
                case "openapi" -> openapi = bool(k, v);
                case "actuator" -> actuator = bool(k, v);
                case "docker" -> docker = bool(k, v);
                case "ci" -> ci = bool(k, v);
                case "zip" -> zip = bool(k, v);
                case "force" -> force = bool(k, v);
                case "out" -> out = v;
                case "description" -> description = v;
                default -> {
                    System.err.println("Unknown option: --" + k);
                    System.err.println("Run with --help to see all options.");
                    System.exit(2);
                }
            }
        }
    }

    private static String pick(String key, String value) {
        String v = value.toLowerCase(Locale.ROOT);
        // friendly aliases
        v = switch (v) {
            case "postgresql" -> "postgres";
            case "mongodb" -> "mongo";
            case "junit5" -> "junit";
            case "rabbit" -> "rabbitmq";
            case "activemq" -> "artemis";
            default -> v;
        };
        if (!ALLOWED.get(key).contains(v)) {
            System.err.println("Invalid value for --" + key + ": " + value);
            System.err.println("Allowed: " + String.join(", ", ALLOWED.get(key)));
            System.exit(2);
        }
        return v;
    }

    private static boolean bool(String key, String value) {
        return switch (value.toLowerCase(Locale.ROOT)) {
            case "true", "yes", "y", "1", "" -> true;
            case "false", "no", "n", "0" -> false;
            default -> {
                System.err.println("Invalid boolean for --" + key + ": " + value);
                System.exit(2);
                yield false;
            }
        };
    }

    public boolean boot3() { return "3".equals(boot); }
    public boolean sqlDb() { return switch (db) { case "postgres", "mysql", "mariadb", "h2" -> true; default -> false; }; }

    /**
     * Enforces cross-option compatibility. Returns human-readable notes about
     * every adjustment so the user knows exactly what Loom decided and why.
     */
    public List<String> normalize() {
        List<String> notes = new ArrayList<>();

        name = sanitizeArtifact(name);

        // --- Boot line vs Java version ---
        if (boot3() && (javaVersion.equals("8") || javaVersion.equals("11"))) {
            notes.add("Spring Boot 3 requires Java 17+ -> Java version bumped to 17.");
            javaVersion = "17";
        }

        // --- Language rules ---
        if (lang.equals("kotlin") && lombok) {
            notes.add("Lombok is unnecessary with Kotlin (data classes) -> Lombok disabled.");
            lombok = false;
        }
        if (lang.equals("kotlin") && tests.equals("testng")) {
            notes.add("Kotlin scaffolding ships with JUnit 5 -> TestNG replaced by JUnit.");
            tests = "junit";
        }

        // --- Web / server rules ---
        if (web.equals("webflux")) {
            if (!server.equals("netty")) {
                server = "netty"; // Reactor Netty is the WebFlux default; keep it deterministic
            }
            if (json.equals("gson")) {
                notes.add("WebFlux codecs are Jackson-based; Gson is MVC-only -> Jackson selected.");
                json = "jackson";
            }
        }
        if (web.equals("mvc") && server.equals("netty")) {
            server = "tomcat";
        }
        if (web.equals("none")) {
            server = "netty"; // irrelevant, neutral value
            if (openapi) {
                notes.add("OpenAPI needs a web layer -> springdoc skipped.");
                openapi = false;
            }
        }

        // --- HTTP client rules ---
        if (!boot3() && http.equals("restclient")) {
            notes.add("RestClient needs Spring Framework 6.1 (Boot 3.2+) -> RestTemplate generated instead.");
            http = "resttemplate";
        }

        // --- Database / data-access rules ---
        if (db.equals("none")) {
            data = "none";
            migrations = "none";
        } else if (db.equals("mongo")) {
            data = "mongo";
            if (!migrations.equals("none")) {
                notes.add("Flyway/Liquibase target SQL databases; MongoDB migrations (Mongock) are on the roadmap -> skipped.");
                migrations = "none";
            }
        } else { // SQL database
            if (data.equals("auto") || data.equals("mongo")) {
                data = web.equals("webflux") && boot3() ? "r2dbc" : "jpa";
            }
            if (data.equals("r2dbc") && !boot3()) {
                notes.add("R2DBC scaffolding targets Boot 3 -> JPA selected for the Boot 2.7 line.");
                data = "jpa";
            }
            if (web.equals("webflux") && (data.equals("jpa") || data.equals("jdbc"))) {
                notes.add("Blocking " + data.toUpperCase(Locale.ROOT)
                        + " on the WebFlux event loop will hurt throughput; consider R2DBC.");
            }
        }

        // --- Testcontainers ---
        if (tc && tests.equals("testng")) {
            notes.add("Testcontainers auto-wiring is generated for JUnit; with TestNG you get the "
                    + "dependencies but manage container lifecycle yourself.");
        }
        if (tc && !boot3()) {
            notes.add("Boot 2.7 predates @ServiceConnection: Testcontainers dependencies added, "
                    + "tests fall back to H2; wire @DynamicPropertySource for real-container tests.");
        }

        // --- EasyMock / TestNG on Java 8 need older lines ---
        // handled in Resolver via version catalog

        if (packageName == null || packageName.isBlank()) {
            packageName = sanitizePackage(groupId + "." + name);
        } else {
            packageName = sanitizePackage(packageName);
        }
        return notes;
    }

    static String sanitizeArtifact(String raw) {
        String s = raw.trim().toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9-]+", "-");
        s = s.replaceAll("^-+|-+$", "");
        return s.isEmpty() ? "demo" : s;
    }

    static String sanitizePackage(String raw) {
        StringBuilder sb = new StringBuilder();
        for (String part : raw.toLowerCase(Locale.ROOT).split("\\.")) {
            String p = part.replaceAll("[^a-z0-9]", "");
            if (p.isEmpty()) continue;
            if (Character.isDigit(p.charAt(0))) p = "_" + p;
            if (sb.length() > 0) sb.append('.');
            sb.append(p);
        }
        return sb.length() == 0 ? "com.example.demo" : sb.toString();
    }

    /** PascalCase application class name derived from the artifact id. */
    public String appClass() {
        StringBuilder sb = new StringBuilder();
        for (String part : name.split("[^A-Za-z0-9]+")) {
            if (part.isEmpty()) continue;
            sb.append(Character.toUpperCase(part.charAt(0)));
            if (part.length() > 1) sb.append(part.substring(1));
        }
        if (sb.length() == 0) sb.append("Demo");
        if (Character.isDigit(sb.charAt(0))) sb.insert(0, "App");
        return sb + "Application";
    }
}
